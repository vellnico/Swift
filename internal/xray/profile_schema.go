package xray

// Field describes one editable profile parameter. The UI builds forms from
// this schema; labels and hints live in i18n under profiles.fields.<Name>.
type Field struct {
	Name        string   `json:"name"`
	Type        string   `json:"type"` // text | number | select | list | secret | switch
	Recommended any      `json:"recommended,omitempty"`
	Options     []string `json:"options,omitempty"`
	Advanced    bool     `json:"advanced"`
	Min         int      `json:"min,omitempty"`
	Max         int      `json:"max,omitempty"`
	Pattern     string   `json:"pattern,omitempty"`
	Regenerate  bool     `json:"regenerate,omitempty"` // value can be regenerated by the server
}

// DefaultFingerprint is the uTLS fingerprint clients use for REALITY. Not "chrome": the
// ClientHello Xray sends as chrome is cut by Russian DPI on port 443 (see SPEC 15).
const DefaultFingerprint = "firefox"

var Fingerprints = []string{"chrome", "firefox", "safari", "ios", "android", "edge", "random"}
var XHTTPModes = []string{"auto", "packet-up", "stream-up", "stream-one"}

const hostPortPattern = `^[A-Za-z0-9.-]+:[0-9]{1,5}$`

func realityFields(defaultPort int) []Field {
	return []Field{
		{Name: "name", Type: "text"},
		{Name: "port", Type: "number", Recommended: defaultPort, Min: 1, Max: 65535},
		{Name: "serverNames", Type: "list"},
		{Name: "target", Type: "text", Pattern: hostPortPattern},
		{Name: "fingerprint", Type: "select", Recommended: DefaultFingerprint, Options: Fingerprints},
		{Name: "shortIds", Type: "list", Advanced: true, Pattern: `^[0-9a-f]{0,16}$`, Regenerate: true},
		{Name: "privateKey", Type: "secret", Advanced: true, Regenerate: true},
	}
}

// Schema returns the fields of each profile kind in display order.
func Schema() map[Kind][]Field {
	xhttp := realityFields(DefaultPort(KindXHTTP))
	xhttp = append(xhttp[:4:4],
		Field{Name: "path", Type: "text", Pattern: `^/[A-Za-z0-9/_-]*$`, Regenerate: true},
		Field{Name: "mode", Type: "select", Recommended: "auto", Options: XHTTPModes},
	)
	xhttp = append(xhttp, realityFields(0)[4:]...)
	return map[Kind][]Field{
		KindVision: realityFields(DefaultPort(KindVision)),
		KindXHTTP:  xhttp,
		KindHysteria2: {
			{Name: "name", Type: "text"},
			{Name: "port", Type: "number", Recommended: DefaultPort(KindHysteria2), Min: 1, Max: 65535},
			{Name: "obfs", Type: "switch", Recommended: true},
			{Name: "obfsPassword", Type: "secret", Advanced: true, Regenerate: true},
		},
	}
}

// DefaultPort is the recommended port of a profile kind (SPEC 6.1).
func DefaultPort(k Kind) int {
	if k == KindXHTTP {
		return 8443
	}
	return 443
}
